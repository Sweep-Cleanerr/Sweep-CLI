use std::env;
use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=cleaners");

    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("cleaners");
    let mut names: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            if path.extension().and_then(|e| e.to_str()) == Some("toml") {
                Some(path.file_name()?.to_string_lossy().into_owned())
            } else {
                None
            }
        })
        .collect();
    names.sort();

    let mut code = String::from("// Generated by build.rs from cleaners/*.toml.\n");
    code.push_str("pub static BUILTIN_CLEANERS: &[(&str, &str)] = &[\n");
    for name in &names {
        let relative = format!("/cleaners/{name}");
        code.push_str(&format!(
            "    ({name:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {relative:?}))),\n"
        ));
    }
    code.push_str("];\n");

    let out = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("builtin_cleaners.rs");
    fs::write(out, code).expect("write generated cleaner table");
}
