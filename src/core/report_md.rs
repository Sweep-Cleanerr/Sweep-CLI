//! Markdown report (`--markdown PATH`).
//!
//! Plain-text sibling of the HTML report: pasteable into CI, GitHub
//! issues or PR comments. No dependencies; same summary and
//! per-category sections, different formatting.

use std::collections::BTreeMap;
use std::path::Path;

use super::report::Report;

/// Collapse line breaks to spaces; CRLF must become one space.
fn flatten(text: &str) -> String {
    text.replace("\r\n", "\n").replace(['\n', '\r'], " ")
}

/// Escape for table cells: backslash and pipe.
fn cell(text: &str) -> String {
    flatten(text).replace('\\', "\\\\").replace('|', "\\|")
}

/// Inline code span safe to render: escapes pipe, sizes the fence
/// from the longest inner backtick run, pads the edges.
fn inline(text: &str) -> String {
    let escaped = flatten(text).replace('|', "\\|");
    if escaped.is_empty() {
        return "\u{2014}".to_string();
    }
    let mut longest = 0usize;
    let mut run = 0usize;
    for ch in escaped.chars() {
        if ch == '`' {
            run += 1;
            longest = longest.max(run);
        } else {
            run = 0;
        }
    }
    let fence = "`".repeat(longest + 1);
    format!("{fence} {escaped} {fence}")
}

fn human(bytes: u64) -> String {
    crate::fsutil::bytes_to_human(bytes, false)
}

/// (cleaner, option) -> (files, bytes) summary.
fn by_option(report: &Report) -> BTreeMap<(String, String), (u64, u64)> {
    let mut out: BTreeMap<(String, String), (u64, u64)> = BTreeMap::new();
    for entry in &report.entries {
        if entry.reclaimed == 0 && !entry.kind.counts_as_deleted() {
            continue;
        }
        let slot = out
            .entry((entry.cleaner.clone(), entry.option.clone()))
            .or_insert((0, 0));
        slot.0 += u64::from(entry.kind.counts_as_deleted());
        slot.1 += entry.reclaimed;
    }
    out
}

/// Render the report as Markdown.
pub fn to_markdown(report: &Report, title: &str) -> String {
    let mut out = String::new();

    out.push_str(&format!("# {}\n\n", cell(title)));

    out.push_str("| reclaimed | files removed | special ops | skipped | errors | duration |\n");
    out.push_str("| --- | --- | --- | --- | --- | --- |\n");
    out.push_str(&format!(
        "| {} | {} | {} | {} | {} | {} |\n\n",
        human(report.reclaimed()),
        report.files_removed(),
        report.special_operations(),
        report.skipped(),
        report.errors.len(),
        if report.duration_ms > 0 {
            format!("{} ms", report.duration_ms)
        } else {
            "\u{2014}".to_string()
        },
    ));
    if report.aborted {
        out.push_str("> **Aborted** - the run was cancelled before completion.\n\n");
    }

    let cats = by_option(report);
    if !cats.is_empty() {
        out.push_str("## By category\n\n");
        out.push_str("| cleaner.option | files | size |\n| --- | --- | --- |\n");
        for ((cleaner, option), (files, bytes)) in &cats {
            out.push_str(&format!(
                "| {}.{} | {} | {} |\n",
                cell(cleaner),
                cell(option),
                files,
                human(*bytes)
            ));
        }
        out.push('\n');
    }

    const ROW_CAP: usize = 500;
    if !report.entries.is_empty() {
        out.push_str("## Entries\n\n");
        out.push_str("| kind | target | detail | path | size |\n| --- | --- | --- | --- | --- |\n");
        for entry in report.entries.iter().take(ROW_CAP) {
            out.push_str(&format!(
                "| {} | {}.{} | {} | {} | {} |\n",
                cell(entry.kind.label()),
                cell(&entry.cleaner),
                cell(&entry.option),
                inline(&entry.label),
                entry
                    .path
                    .as_ref()
                    .map(|p| inline(&p.display().to_string()))
                    .unwrap_or_else(|| "\u{2014}".to_string()),
                if entry.reclaimed > 0 {
                    human(entry.reclaimed)
                } else {
                    "\u{2014}".to_string()
                },
            ));
        }
        if report.entries.len() > ROW_CAP {
            out.push_str(&format!(
                "\n_{} more entries omitted._\n",
                report.entries.len() - ROW_CAP
            ));
        }
        out.push('\n');
    }

    if !report.errors.is_empty() {
        out.push_str("## Failures\n\n");
        out.push_str("| target | message |\n| --- | --- |\n");
        for failure in &report.errors {
            out.push_str(&format!(
                "| {}.{} | {} |\n",
                cell(&failure.cleaner),
                cell(&failure.option),
                cell(&failure.message)
            ));
        }
        out.push('\n');
    }

    out.push_str(&format!("---\n_Generated by sweep {}._\n", crate::VERSION));
    out
}

/// Write the report to a file (creating the parent dir).
pub fn write_markdown(report: &Report, title: &str, dest: &Path) -> std::io::Result<()> {
    if let Some(parent) = dest.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)?;
        }
    }
    std::fs::write(dest, to_markdown(report, title))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::report::{Entry, EntryKind};

    #[test]
    fn table_cells_and_code_spans_are_safe() {
        let mut report = Report::new();
        report.push(Entry::new(
            EntryKind::Delete,
            "a|b",
            "o",
            "has `tick` and | pipe",
            None,
            42,
        ));
        let md = to_markdown(&report, "Title | One");
        assert!(md.starts_with("# Title \\| One"));
        assert!(md.contains("`` has `tick` and \\| pipe ``"));
        assert!(md.contains("---\n"));
    }

    #[test]
    fn empty_report_still_renders_header() {
        let report = Report::new();
        let md = to_markdown(&report, "Empty");
        assert!(md.contains("# Empty"));
        assert!(md.contains("| reclaimed |"));
    }
}
